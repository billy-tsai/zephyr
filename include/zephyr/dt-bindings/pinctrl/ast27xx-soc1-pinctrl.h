#ifndef ZEPHYR_INCLUDE_DT_BINDINGS_PINCTRL_AST27XX_SOC1_PINCTRL_H_
#define ZEPHYR_INCLUDE_DT_BINDINGS_PINCTRL_AST27XX_SOC1_PINCTRL_H_

#define AST27XX_SOC1_BALL_C25 0U
#define AST27XX_SOC1_BALL_C24 1U
#define AST27XX_SOC1_BALL_A17 2U
#define AST27XX_SOC1_BALL_A16 3U
#define AST27XX_SOC1_BALL_M16 4U
#define AST27XX_SOC1_BALL_A15 5U

#define AST27XX_SOC1_PINMUX(ball, func) ((AST27XX_SOC1_BALL_##ball << 8U) | (func))

#define FWSPICS0_C25  AST27XX_SOC1_PINMUX(C25, 0U)
#define FWSPICK_C24   AST27XX_SOC1_PINMUX(C24, 0U)
#define FWSPIMOSI_A17 AST27XX_SOC1_PINMUX(A17, 0U)
#define FWSPIMISO_A16 AST27XX_SOC1_PINMUX(A16, 0U)
#define FWSPIDQ2_M16  AST27XX_SOC1_PINMUX(M16, 1U)
#define FWSPIDQ3_A15  AST27XX_SOC1_PINMUX(A15, 1U)

#endif /* ZEPHYR_INCLUDE_DT_BINDINGS_PINCTRL_AST27XX_SOC1_PINCTRL_H_ */
